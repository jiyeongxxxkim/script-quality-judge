import json

def _j(d): return json.dumps(d, ensure_ascii=False)

def _item(flag=False, ev=(), src=(), reason="", conf="high", fatal=None):
    d = {"flag": flag, "evidence": list(ev)}
    if src != "-": d["source_quote"] = list(src)
    d.update(reason=reason, confidence=conf)
    if fatal is not None: d["fatal_candidate"] = fatal
    return d

def _f(**over):
    out = {"F1": _item(), "F2": _item(), "F3": _item(fatal=False)}
    out.update(over); return out

def _p(**over):
    out = {"R1": _item(src="-", fatal=False), "R2": _item(src="-"), "N1": _item(src="-"), "N2": _item(src="-"), "N3": _item(src="-"),
           "H1": {"present": False, "evidence": [], "reason": ""}}
    out.update(over); return out

